// Languages offered in the switcher, by their own names.
var languages = []struct{ Code, Name string }{{"am", "አማርኛ"}, {"en", "English"}, {"om", "Afaan Oromoo"}, {"ti", "ትግርኛ"}}

func translate(lang, key string, args ...string) string {
	v, ok := texts[lang][key]
	if !ok {
		v, ok = texts["en"][key]
		if !ok {
			v = key
		}
	}
	for i := 0; i+1 < len(args); i += 2 {
		v = strings.ReplaceAll(v, "{"+args[i]+"}", args[i+1])
	}
	return v
}
